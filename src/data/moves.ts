const REACH_SCALE: Record<FighterId, number> = {
  modi: 1.02,
  rahul: 1.03,
  didi: 0.95,
  trump: 1.07,
  yogi: 1.0,
  nitin: 1.02,
  ravi: 1.0,
  lalu: 0.97,
  amit: 1.0,
  dhruv: 1.0,
  mbapu: 1.04,
};

export function getMoveReach(fighterId: FighterId, moveId: MoveId): ReachSpec {
  const base = DEFAULT_REACH[moveId];
  const scale = REACH_SCALE[fighterId] ?? 1;
  return {
    reach: base.reach * scale,
    height: base.height * scale,
  };
}

